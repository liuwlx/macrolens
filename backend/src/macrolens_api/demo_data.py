def _demo_uuid(kind: str, value: str) -> UUID:
    return uuid5(DEMO_NAMESPACE, f"{kind}:{value}")


@dataclass(frozen=True, slots=True)
class DemoTaxonomyNode:
    code: str
    parent_code: str | None
    name_zh: str
    name_en: str | None
    node_type: str
    sort_order: int
    series_codes: tuple[str, ...]
    icon_key: str | None = None

    @property
    def id(self) -> UUID:
        return _demo_uuid("taxonomy", self.code)


