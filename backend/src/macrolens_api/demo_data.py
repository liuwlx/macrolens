def _csv_safe(value: object) -> str:
    text = str(value).replace("\t", " ").replace("\r", " ").replace("\n", " ")
    return "'" + text if text.startswith(("=", "+", "-", "@")) else text


def demo_series_csv(
    series_id: UUID,
    *,
    start: date | None,
    end: date | None,
    transform: str,
) -> bytes:
    response = demo_observations(series_id, start=start, end=end, transform=transform)
    output = io.StringIO(newline="")
    writer = csv.writer(output)
    writer.writerow(
        [
            "series_id",
            "canonical_code",
            "name_zh",
            "period_start",
            "period_end",
            "value",
            "status",
            "published_at",
            "vintage_at",
            "data_as_of",
            "data_mode",
            "transform",
            "unit",
            "provider",
            "attribution",
        ]
    )
    for point in response.data:
        writer.writerow(
            [
                response.series.id,
                _csv_safe(response.series.canonical_code),
                _csv_safe(response.series.name_zh),
                point.period_start,
                point.period_end,
                point.value if point.value is not None else "",
                point.status,
                point.published_at.isoformat() if point.published_at else "",
                point.vintage_at.isoformat(),
                DEMO_AS_OF.isoformat(),
                "demo",
                transform,
                response.meta.unit,
                DEMO_PROVIDER.code,
                DEMO_PROVIDER.attribution or "",
            ]
        )
    return ("\ufeff" + output.getvalue()).encode("utf-8")


