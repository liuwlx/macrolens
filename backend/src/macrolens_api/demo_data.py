def _serialize_taxonomy_node(node: DemoTaxonomyNode) -> dict[str, Any]:
    registry = get_demo_registry()
    return {
        "id": str(node.id),
        "code": node.code,
        "name_zh": node.name_zh,
        "name_en": node.name_en,
        "node_type": node.node_type,
        "icon_key": node.icon_key,
        "description": None,
        "series": [
            {
                "id": str(registry.series_by_code[code].id),
                "canonical_code": code,
                "name_zh": registry.series_by_code[code].name_zh,
                "name_en": registry.series_by_code[code].name_en,
                "frequency": registry.series_by_code[code].frequency,
                "unit": registry.series_by_code[code].unit_label_zh,
                "role": "primary",
            }
            for code in node.series_codes
        ],
        "children": [
            _serialize_taxonomy_node(child)
            for child in registry.children_by_code.get(node.code, ())
        ],
    }


def demo_taxonomy(tree_code: str, *, include_series: bool = True) -> dict[str, Any]:
    registry = get_demo_registry()
    if tree_code != registry.tree_code:
        raise AppError(404, "分类树不存在", "没有找到指定分类树。", "taxonomy_not_found")
    nodes = [_serialize_taxonomy_node(node) for node in registry.children_by_code[None]]
    if not include_series:
        pending = list(nodes)
        while pending:
            item = pending.pop()
            item["series"] = []
            pending.extend(item["children"])
    return {"tree_code": tree_code, "nodes": nodes, "data_mode": "demo"}


def demo_taxonomy_children(
    tree_code: str,
    *,
    parent_id: UUID | None,
    q: str | None,
    scope: str,
) -> TaxonomyChildrenResponse:
    registry = get_demo_registry()
    if tree_code != registry.tree_code:
        raise AppError(404, "分类树不存在", "没有找到指定分类树。", "taxonomy_not_found")
    parent = registry.nodes_by_id.get(parent_id) if parent_id is not None else None
    if parent_id is not None and parent is None:
        raise AppError(404, "分类节点不存在", "没有找到指定父节点。", "taxonomy_node_not_found")
    visible = (
        registry.nodes
        if scope == "all"
        else registry.children_by_code.get(parent.code if parent else None, ())
    )
    if q and q.strip():
        needle = q.strip().casefold()
        visible = tuple(
            node
            for node in visible
            if needle in node.code.casefold()
            or needle in node.name_zh.casefold()
            or needle in (node.name_en or "").casefold()
        )
    nodes = [
        TaxonomyChildNode(
            id=node.id,
            code=node.code,
            name_zh=node.name_zh,
            name_en=node.name_en,
            node_type=node.node_type,
            icon_key=node.icon_key,
            has_children=bool(registry.children_by_code.get(node.code)),
            direct_series_count=len(node.series_codes),
            descendant_series_count=len(registry.leaf_series_codes(node.code)),
        )
        for node in visible
    ]
    direct_series = (
        [_summary(registry.series_by_code[code]) for code in parent.series_codes]
        if parent is not None
        else []
    )
    return TaxonomyChildrenResponse(
        tree_code=tree_code,
        parent_id=parent_id,
        nodes=nodes,
        series=direct_series,
        data_mode="demo",
    )


def _metric(value: Decimal | None, unit: str, *, basis: str | None = None) -> BrowserMetric:
    return BrowserMetric(
        value=value,
        unit=unit,
        status="available" if value is not None else "unavailable",
        basis=basis,
        reason_code=None if value is not None else "insufficient_history",
        reason=None if value is not None else "Insufficient deterministic demo history.",
    )


def _browser_item(series: DemoSeries, taxonomy_order: int) -> SeriesBrowserItem:
    points = list(demo_points(series.canonical_code))
    current = points[-1]
    previous = points[-2]
    assert current.value is not None and previous.value is not None
    lag = PERIODS_PER_YEAR[series.frequency]
    yoy_value: Decimal | None = None
    if len(points) > lag and points[-1 - lag].value not in {None, Decimal(0)}:
        base = points[-1 - lag].value
        assert base is not None
        yoy_value = ((current.value / base) - 1) * 100
    change_unit = (
        "pp" if series.unit_code in {"percent", "percentage_point"} else series.unit_label_zh
    )
    period_change = ((current.value / previous.value) - 1) * 100 if previous.value else None

    def observation(point: Point) -> BrowserObservation:
        assert isinstance(point.vintage_at, datetime)
        return BrowserObservation(
            period_start=point.period_start,
            period_end=point.period_end,
            value=point.value,
            published_at=point.published_at if isinstance(point.published_at, datetime) else None,
            vintage_at=point.vintage_at,
        )

    return SeriesBrowserItem(
        series=_summary(series),
        current=observation(current),
        previous=observation(previous),
        change=_metric((current.value - previous.value).quantize(Decimal("0.01")), change_unit),
        period_change=_metric(
            period_change.quantize(Decimal("0.01")) if period_change is not None else None,
            "%",
            basis="period",
        ),
        yoy=_metric(
            yoy_value.quantize(Decimal("0.01")) if yoy_value is not None else None, "%", basis="yoy"
        ),
        license=DEMO_LICENSE,
        display_denied=False,
        source_status="ready",
        unavailable_reason_code=None,
        taxonomy_order=taxonomy_order,
        availability="available",
    )


def _facets(series: list[DemoSeries]) -> BrowserFacets:
    def values(attribute: str) -> list[BrowserFacetValue]:
        counts: dict[str, int] = {}
        for item in series:
            value = str(getattr(item, attribute))
            counts[value] = counts.get(value, 0) + 1
        return [
            BrowserFacetValue(value=value, label=value, count=count)
            for value, count in sorted(counts.items())
        ]

    return BrowserFacets(
        provider=[
            BrowserFacetValue(value=DEMO_PROVIDER.code, label=DEMO_PROVIDER.name, count=len(series))
        ],
        theme=values("theme"),
        frequency=values("frequency"),
        unit=values("unit_code"),
        seasonal_adjustment=values("seasonal_adjustment"),
    )


def demo_series_browser(
    *,
    q: str | None,
    node_id: UUID | None,
    provider: str | None,
    theme: str | None,
    frequency: str | None,
    unit: str | None,
    seasonal_adjustment: str | None,
    published_from: date | None,
    published_to: date | None,
    sort: str,
    order: str,
    limit: int,
    offset: int,
) -> SeriesBrowserResponse:
    registry = get_demo_registry()
    allowed_codes: set[str] | None = None
    if node_id is not None:
        node = registry.nodes_by_id.get(node_id)
        if node is None:
            raise AppError(
                404, "分类节点不存在", "没有找到指定分类节点。", "taxonomy_node_not_found"
            )
        allowed_codes = set(registry.leaf_series_codes(node.code))
    series = list(registry.series)
    if allowed_codes is not None:
        series = [item for item in series if item.canonical_code in allowed_codes]
    if q and q.strip():
        needle = q.strip().casefold()
        series = [
            item
            for item in series
            if needle in item.canonical_code.casefold()
            or needle in item.name_zh.casefold()
            or needle in (item.name_en or "").casefold()
        ]
    if provider and provider != DEMO_PROVIDER.code:
        series = []
    if theme:
        series = [item for item in series if item.theme == theme]
    if frequency:
        series = [item for item in series if item.frequency == frequency]
    if unit:
        series = [item for item in series if item.unit_code == unit]
    if seasonal_adjustment:
        series = [item for item in series if item.seasonal_adjustment == seasonal_adjustment]
    if published_from or published_to:

        def published_on(item: DemoSeries) -> date:
            published_at = demo_points(item.canonical_code)[-1].published_at
            assert isinstance(published_at, datetime)
            return published_at.date()

        series = [
            item
            for item in series
            if (published_from is None or published_on(item) >= published_from)
            and (published_to is None or published_on(item) <= published_to)
        ]
    order_by_code = {
        code: index
        for index, code in enumerate(code for node in registry.nodes for code in node.series_codes)
    }
    items = [_browser_item(item, order_by_code[item.canonical_code]) for item in series]
    sort_keys = {
        "taxonomy": lambda item: (item.taxonomy_order, item.series.canonical_code),
        "name": lambda item: (item.series.name_zh.casefold(), item.series.canonical_code),
        "current_period": lambda item: item.current.period_start if item.current else date.min,
        "current": lambda item: (
            item.current.value
            if item.current and item.current.value is not None
            else Decimal("-Infinity")
        ),
        "change": lambda item: (
            item.change.value if item.change.value is not None else Decimal("-Infinity")
        ),
        "period_change": lambda item: (
            item.period_change.value
            if item.period_change.value is not None
            else Decimal("-Infinity")
        ),
        "yoy": lambda item: item.yoy.value if item.yoy.value is not None else Decimal("-Infinity"),
    }
    items.sort(key=sort_keys[sort], reverse=order == "desc")
    total = len(items)
    return SeriesBrowserResponse(
        items=items[offset : offset + limit],
        facets=_facets(series),
        pagination=BrowserPagination(total=total, limit=limit, offset=offset),
        data_as_of=DEMO_AS_OF,
        data_mode="demo",
    )


def demo_observations(
    series_id: UUID,
    *,
    start: date | None,
    end: date | None,
    transform: str,
) -> ObservationResponse:
    series = _series_or_404(series_id)
    points = [
        point
        for point in demo_points(series.canonical_code)
        if (start is None or point.period_start >= start)
        and (end is None or point.period_start <= end)
    ]
    transformed = transform_points(points, transform, series.frequency)
    return ObservationResponse(
        series=_summary(series),
        data=[
            ObservationPoint(
                period_start=point.period_start,
                period_end=point.period_end,
                value=point.value,
                value_text=point.value_text,
                status=point.status,
                published_at=point.published_at
                if isinstance(point.published_at, datetime)
                else None,
                vintage_at=point.vintage_at
                if isinstance(point.vintage_at, datetime)
                else DEMO_AS_OF,
            )
            for point in transformed
        ],
        meta=ObservationMeta(
            data_as_of=DEMO_AS_OF,
            vintage=DEMO_AS_OF.isoformat(),
            transform=transform,
            frequency=series.frequency,
            unit=series.unit_label_zh if transform in {"level", "difference"} else "%",
            lineage=LineageInfo(
                provider=DEMO_PROVIDER.code,
                dataset="deterministic-demo",
                provider_series_id=series.canonical_code,
                source_series_id=int.from_bytes(
                    hashlib.sha256(series.canonical_code.encode()).digest()[:4], "big"
                ),
                source_locator={"mode": "demo", "source_registry": series.source_name},
            ),
            license=DEMO_LICENSE,
            data_mode="demo",
        ),
    )


def demo_revisions(series_id: UUID, *, start: date | None, end: date | None) -> RevisionResponse:
    series = _series_or_404(series_id)
    points = [
        point
        for point in demo_points(series.canonical_code)
        if (start is None or point.period_start >= start)
        and (end is None or point.period_start <= end)
    ][-24:]
    items: list[RevisionItem] = []
    for index, point in enumerate(points):
        assert point.value is not None and isinstance(point.vintage_at, datetime)
        delta = Decimal((index % 5) - 2) / Decimal(100)
        first_vintage = point.vintage_at - timedelta(days=7)
        items.append(
            RevisionItem(
                period_start=point.period_start,
                first_value=point.value - delta,
                latest_value=point.value,
                revision=delta,
                first_vintage_at=first_vintage,
                latest_vintage_at=point.vintage_at,
                versions=2,
            )
        )
    return RevisionResponse(series_id=series_id, items=items, data_as_of=DEMO_AS_OF)


def _statistics(points: list[Point]) -> SeriesStatistics:
    values = [point.value for point in points if point.value is not None]
    if not values:
        return SeriesStatistics(
            count=0,
            mean=None,
            median=None,
            min=None,
            max=None,
            stddev=None,
            current_percentile=None,
        )
    mean_value = sum(values, Decimal(0)) / len(values)
    variance = sum((value - mean_value) ** 2 for value in values) / len(values)
    percentile = Decimal(sum(value <= values[-1] for value in values)) * 100 / len(values)
    return SeriesStatistics(
        count=len(values),
        mean=mean_value.quantize(Decimal("0.01")),
        median=Decimal(median(values)).quantize(Decimal("0.01")),
        min=min(values),
        max=max(values),
        stddev=Decimal(str(float(variance) ** 0.5)).quantize(Decimal("0.01")),
        current_percentile=percentile.quantize(Decimal("0.01")),
    )


